"""Resolve the portfolio + research set against NSE's EQUITY_L.csv and write supabase/seed_companies.sql.

Identifiers are never typed from memory: ISIN and name come from NSE, sector and market cap from yfinance.
A symbol that doesn't resolve is reported, not guessed. BSE codes stay empty (BSE's API is unreachable).

    python scripts/resolve_companies.py [--load]
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))

from finn import config, db  # noqa: E402
from finn.sources import fetchers  # noqa: E402


def sql_lit(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main(load: bool) -> None:
    eq = fetchers.nse_equity_list()
    symbols = list(dict.fromkeys(config.PORTFOLIO + config.RESEARCH))
    rows, missing = [], []
    for s in symbols:
        if s not in eq:
            missing.append(s)
            continue
        prof = fetchers.company_profile(s)
        rows.append(dict(symbol=s, name=eq[s]["name"], isin=eq[s]["isin"], bse_code=None,
                         sector=prof.get("industry") or prof.get("sector"), mcap_cr=prof.get("mcap_cr"),
                         is_financial=s in config.FINANCIALS or prof.get("sector") == "Financial Services",
                         in_portfolio=s in config.PORTFOLIO, in_research_set=s in config.RESEARCH))
        print(f"  {s:<11} {rows[-1]['isin']}  {rows[-1]['sector'] or '-':<36} mcap ₹{rows[-1]['mcap_cr']} cr")
    if missing:
        print("NOT FOUND in EQUITY_L:", ", ".join(missing))

    cols = list(rows[0].keys())
    lines = ["-- Generated by scripts/resolve_companies.py from NSE EQUITY_L.csv + yfinance. Do not hand-edit.",
             f"insert into companies ({', '.join(cols)}) values"]
    lines.append(",\n".join("  (" + ", ".join(sql_lit(r[c]) for c in cols) + ")" for r in rows))
    lines.append("on conflict (symbol) do update set " + ", ".join(f"{c} = excluded.{c}" for c in cols[1:])
                 + ", updated_at = now();")
    out = Path(__file__).resolve().parents[1] / "supabase" / "seed_companies.sql"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.name}: {len(rows)} companies")
    if load:
        db.upsert("companies", rows, key=["symbol"])
        print("loaded into", "Supabase" if "supabase" in config.DB_URL else "local dev DB")


if __name__ == "__main__":
    main("--load" in sys.argv)
